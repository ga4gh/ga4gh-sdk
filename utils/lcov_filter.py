"""Remove the PyO3 attribute lines from the coverage report and summarize it.

`make coverage` runs this on `coverage/lcov.info` (see the Coverage section
of `docs/development.md`). Each method of a `#[pymethods]` block, and each
default method that `#[pyclass(eq, eq_int)]` adds, gets a trampoline
generated by PyO3. The instrumentation attributes the trampolines to the
attribute's line and always reports them as not executed, even when tests
call the methods; the code of the methods is measured on its own lines. So
the line and function records of the attribute lines of the bindings
(`python/src/`) are left out: these lines hold no code of this repository.

The summary counts the lines as Codecov does (one line per `DA` record),
per top-level source directory such as `lib/src`.

Usage: `python3 utils/lcov_filter.py coverage/lcov.info [--root DIR]`
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from pathlib import Path
import re
import sys

#: Source files whose PyO3 attribute lines are left out.
BINDINGS = "python/src/"
#: The lines that only hold a PyO3 attribute with generated trampolines, or
#: open a `#[pyclass(...)]` that continues on the next lines.
ATTRIBUTE = re.compile(r"\s*#\[(pymethods\]|pyclass(\(.*\))?\]|pyclass\([^\]]*)\s*")


#: The summary row of source files outside the repository root.
OUTSIDE = "(outside)"


def _relative(path: str, root: Path) -> str | None:
    """Return a report path relative to the repository root.

    Args:
        path: Path of a source file as the report names it; a relative
            path is relative to `root`.
        root: The repository root.

    Returns:
        The POSIX path relative to `root`, or `None` outside of it.
    """
    try:
        return (root / path).resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return None


def _attribute_lines(path: Path) -> set[int]:
    """Find the PyO3 attribute lines of a source file.

    Args:
        path: The source file.

    Returns:
        The numbers of the lines that only hold a PyO3 attribute.
    """
    lines = path.read_text(encoding="utf-8").splitlines()
    return {number for number, line in enumerate(lines, 1) if ATTRIBUTE.fullmatch(line)}


def filter_report(report: str, root: Path) -> tuple[str, int]:
    """Remove the records of PyO3 attribute lines of the bindings.

    The `DA` (line) and `FN` (function) records of these lines go, with the
    `FNDA` records of the removed functions; `LF`, `LH`, `FNF` and `FNH` are
    counted again.

    Args:
        report: The LCOV report.
        root: The repository root, to which the report's paths belong.

    Returns:
        The filtered report and the number of removed `DA` records.
    """
    out: list[str] = []
    dropped = 0
    skip: set[int] = set()
    functions: set[str] = set()
    found = hit = functions_found = functions_hit = 0
    for line in report.splitlines(keepends=True):
        if line.startswith("SF:"):
            source = line[3:].rstrip("\n")
            relative = _relative(source, root)
            # A missing source raises: the report doesn't match the checkout
            in_bindings = relative is not None and relative.startswith(BINDINGS)
            skip = _attribute_lines(root / relative) if in_bindings else set()
            functions = set()
            found = hit = functions_found = functions_hit = 0
        elif line.startswith("FN:"):
            number, name = line[3:].rstrip("\n").split(",", 1)
            if int(number) in skip:
                functions.add(name)
                continue
            functions_found += 1
        elif line.startswith("FNDA:"):
            count, name = line[5:].rstrip("\n").split(",", 1)
            if name in functions:
                continue
            functions_hit += int(count) > 0
        elif line.startswith("DA:"):
            number, count = line[3:].split(",")[:2]
            if int(number) in skip:
                dropped += 1
                continue
            found += 1
            hit += int(count) > 0
        elif line.startswith("FNF:"):
            line = f"FNF:{functions_found}\n"
        elif line.startswith("FNH:"):
            line = f"FNH:{functions_hit}\n"
        elif line.startswith("LF:"):
            line = f"LF:{found}\n"
        elif line.startswith("LH:"):
            line = f"LH:{hit}\n"
        out.append(line)
    return "".join(out), dropped


def summarize(report: str, root: Path) -> str:
    """Count the covered lines per top-level source directory.

    Args:
        report: The LCOV report.
        root: The repository root, to which the report's paths belong.

    Returns:
        A table of lines, missed lines and coverage per directory, with a
        `TOTAL` row; files outside `root` count in one `(outside)` row.
    """
    counts: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    directory = ""
    for line in report.splitlines():
        if line.startswith("SF:"):
            relative = _relative(line[3:], root)
            directory = (
                OUTSIDE if relative is None else "/".join(relative.split("/")[:2])
            )
        elif line.startswith("DA:"):
            counts[directory][0] += 1
            counts[directory][1] += int(line[3:].split(",")[1]) == 0
    rows = sorted(counts.items())
    rows.append(("TOTAL", [sum(c[0] for _, c in rows), sum(c[1] for _, c in rows)]))
    table = f"{'Directory':<12} {'Lines':>7} {'Missed':>8} {'Covered':>8}\n"
    for name, (lines, missed) in rows:
        share = 100 * (lines - missed) / lines if lines else 100.0
        table += f"{name:<12} {lines:>7} {missed:>8} {share:>7.2f}%\n"
    return table


def main(argv: list[str] | None = None) -> int:
    """Filter an LCOV file in place and print its summary.

    Args:
        argv: The command line arguments, without the program name.

    Returns:
        The exit status.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("lcov", type=Path, help="LCOV file to filter in place")
    parser.add_argument("--root", type=Path, default=Path.cwd(), help="repository root")
    args = parser.parse_args(argv)
    report, dropped = filter_report(args.lcov.read_text(encoding="utf-8"), args.root)
    args.lcov.write_text(report, encoding="utf-8")
    print(f"Dropped {dropped} PyO3 attribute lines")
    print(summarize(report, args.root), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
